"""M17.2 browser smoke: PHB-indexed backgrounds, feat eligibility, +1 triple, and source labeling."""
from pathlib import Path
import base64,re,shutil,json
from playwright.sync_api import sync_playwright
BASE=Path(__file__).resolve().parents[1]
html=(BASE/'index.html').read_text(encoding='utf-8')
html=html.replace('<link rel="stylesheet" href="css/style.css">','<style>'+(BASE/'css/style.css').read_text()+'</style>')
html=html.replace('</head>', '''<script>Object.defineProperty(window,'indexedDB',{configurable:true,value:undefined});const STORE={};Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>STORE[k]||null,setItem:(k,v)=>STORE[k]=String(v),removeItem:k=>delete STORE[k]}});window.confirm=()=>true;</script></head>''')
html=re.sub(r'<script src="([^"]+)"></script>',lambda m:'<script>'+(BASE/m.group(1)).read_text().replace('</script>',r'<\/script>')+'</script>',html)
for name in ('butterfly.svg','folio-seal.svg','folio-book.svg'):
    html=html.replace('assets/'+name,'data:image/svg+xml;base64,'+base64.b64encode((BASE/'assets'/name).read_bytes()).decode())
with sync_playwright() as p:
    executable=shutil.which('chromium') or shutil.which('google-chrome')
    browser=p.chromium.launch(headless=True,executable_path=executable,args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1280,'height':900});errors=[]
    page.on('pageerror',lambda err:errors.append(str(err)))
    page.set_content(html,wait_until='domcontentloaded')
    page.locator('[data-action=library-new-character]').first.click()
    f=page.locator('#library-character-create');assert f.is_visible()
    assert f.locator('select[name=backgroundId] option').count()==17
    assert f.locator('select[name=featId] option').count()>=25
    assert 'PHB reference' in f.locator('select[name=backgroundId]').inner_text()
    f.locator('input[name=name]').fill('Marigold')
    f.locator('select[name=classId]').select_option('class:fighter')
    f.locator('select[name=speciesId]').select_option('species:human')
    f.locator('select[name=backgroundId]').select_option('background:artisan')
    f.locator('select[name=backgroundMethod]').select_option('triple')
    assert f.locator('select[name=backgroundPlus]').is_disabled()
    assert f.locator('select[name=backgroundOne]').is_disabled()
    preview=page.locator('#builder-live-preview')
    assert 'FINAL SCORES' in preview.inner_text()
    assert 'Crafter' in preview.inner_text()
    assert '11' in preview.inner_text()
    assert 'PHB reference' in f.locator('#builder-background-details').inner_text()
    f.locator('select[name=featId]').select_option('feat:grappler')
    assert 'requires level 4' in preview.inner_text()
    f.locator('input[name=level]').fill('5')
    assert 'Strength or Dexterity 13' in preview.inner_text()
    f.locator('input[name=score-str]').fill('12')
    assert 'Grappler' in preview.inner_text()
    assert 'requires' not in preview.inner_text()
    f.locator('button[type=submit]').click()
    assert page.locator('.library-character').filter(has_text='Marigold').count()==1
    page.locator('[data-action=library-new-character]').first.click()
    f=page.locator('#library-character-create')
    f.locator('input[name=name]').fill('Solstice')
    f.locator('select[name=classId]').select_option('class:wizard')
    f.locator('select[name=backgroundId]').select_option('background:wayfarer')
    f.locator('select[name=backgroundMethod]').select_option('triple')
    assert 'Lucky' in page.locator('#builder-live-preview').inner_text()
    page.locator('.library-dialog .close-modal').click()
    page.locator('[data-action=library-rules]').click()
    personal=json.dumps({'format':'folio-source-pack','version':1,'id':'user-book-notes','name':'Owned Book Notes','description':'My reference metadata','license':'User-provided','published':'2026','entries':[{'id':'scribe-of-stars','name':'Scribe of Stars','category':'background','abilities':['int','wis','cha'],'skills':['Arcana','History'],'tool':'Calligraphers Supplies','feat':'Skilled','description':'A user-entered book option'}]})
    page.locator('#library-source-import-file').set_input_files({'name':'book-notes.json','mimeType':'application/json','buffer':personal.encode()})
    page.get_by_text('Owned Book Notes').wait_for(state='visible')
    page.locator('.library-dialog .close-modal').click()
    page.locator('[data-action=library-new-character]').first.click()
    f=page.locator('#library-character-create')
    assert f.locator('select[name=backgroundId] option').count()==18
    f.locator('input[name=name]').fill('Starling')
    f.locator('select[name=classId]').select_option('class:wizard')
    f.locator('select[name=backgroundId]').select_option('source:user-book-notes:background:scribe-of-stars')
    f.locator('select[name=backgroundPlus]').select_option('int')
    f.locator('select[name=backgroundOne]').select_option('wis')
    assert 'Scribe of Stars' in page.locator('#builder-live-preview').inner_text() or 'Skilled' in page.locator('#builder-live-preview').inner_text()
    assert 'Owned Book Notes' in f.locator('select[name=backgroundId]').inner_text()
    f.locator('button[type=submit]').click()
    assert page.locator('.library-character').filter(has_text='Starling').count()==1
    page.locator('[data-action=library-new-character]').first.click()
    f=page.locator('#library-character-create')
    f.locator('select[name=backgroundId]').select_option('background:wayfarer')
    page.set_viewport_size({'width':390,'height':844})
    assert f.is_visible()
    assert page.locator('.library-dialog').evaluate('e=>e.scrollWidth<=e.clientWidth+5')
    (BASE/'test-output').mkdir(exist_ok=True)
    page.screenshot(path=str(BASE/'test-output'/'milestone17-2-origins-mobile.png'))
    assert not errors,errors
    browser.close()
print('PASS: M17.2 background selection, feats and prerequisites, triple ability increase, narrow layout')
