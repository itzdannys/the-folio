"""Integration smoke: all 2024 PHB Paladin oaths with real save/reopen and mobile."""
from pathlib import Path
import re,base64,shutil
from playwright.sync_api import sync_playwright
BASE=Path(__file__).resolve().parents[1]
html=(BASE/'index.html').read_text('utf8').replace('<link rel="stylesheet" href="css/style.css">','<style>'+(BASE/'css/style.css').read_text()+'</style>')
html=html.replace('</head>','''<script>Object.defineProperty(window,'indexedDB',{configurable:true,value:undefined});const STORE={};Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>STORE[k]||null,setItem:(k,v)=>STORE[k]=String(v),removeItem:k=>delete STORE[k]}});window.confirm=()=>true;</script></head>''')
html=re.sub(r'<script src="([^"]+)"></script>',lambda m:'<script>'+(BASE/m.group(1)).read_text().replace('</script>',r'<\/script>')+'</script>',html)
for name in ('butterfly.svg','folio-seal.svg','folio-book.svg'):
 html=html.replace('assets/'+name,'data:image/svg+xml;base64,'+base64.b64encode((BASE/'assets'/name).read_bytes()).decode())
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path=shutil.which('chromium'),args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1180,'height':850});page.set_default_timeout(8000)
 errors=[];page.on('pageerror',lambda er:errors.append(str(er)))
 page.set_content(html,wait_until='domcontentloaded')
 page.evaluate('window.FolioDice.rollDie=side=>side===20?15:side===8?6:4')
 def create(name,subclass,level):
  page.locator('[data-action=library-new-character]').first.click()
  form=page.locator('#library-character-create')
  form.locator('[name=name]').fill(name)
  form.locator('[name=classId]').select_option('class:paladin')
  form.locator('[name=level]').fill(str(level))
  form.locator('[name=subclassId]').select_option('subclass:'+subclass)
  form.locator('button[type=submit]').click()
  assert not form.count(),page.locator('body').inner_text()[-1300:]
  page.locator('.library-character').filter(has_text=name).locator('[data-action=library-open]').first.click()
 def library():page.locator('[data-action=go-library]').first.click()
 def reopen(name):page.locator('.library-character').filter(has_text=name).locator('[data-action=library-open]').first.click()
 create('Vengeance 2024','oath-of-vengeance',20)
 assert page.locator('[data-action=vengeance-vow]').is_visible()
 page.locator('#vengeance-target').fill('Dire Wolf')
 page.locator('[data-action=vengeance-vow]').click()
 assert 'Active vow: Dire Wolf' in page.locator('body').inner_text()
 page.locator('[data-action=nav][data-tab=spellbook]:visible').first.click()
 marked=page.locator('.spell-book-row').filter(has_text="Hunter's Mark")
 assert marked.count()>0,'Oath of Vengeance Hunter Mark absent from Spellbook'
 marked.first.locator('[data-action=open-cast]').click()
 cast=page.locator('#cast-form')
 cast.locator('[name=cost]').select_option('slot1')
 cast.locator('[name=markTarget]').fill('Dire Wolf')
 cast.locator('button[type=submit]').click()
 page.locator('[data-action=nav][data-tab=inventory]:visible').first.click()
 page.locator('[data-action=weapon-catalog-open]').click()
 page.locator('[data-action=weapon-catalog-add][data-id=longsword]').first.click()
 page.locator('[data-action=close-modal]').last.click()
 page.locator('.ledger-item').filter(has_text='Longsword').locator('[data-action=item-equip]').click()
 page.locator('.ledger-item').filter(has_text='Longsword').locator('[data-action=weapon-attack]').click()
 assert page.locator('[name=vowedTarget]').is_visible()
 page.locator('[name=vowedTarget]').check()
 assert page.locator('[name=markedTarget]').is_visible()
 page.locator('[name=markedTarget]').check()
 page.locator('#weapon-attack-form [name=targetAC]').fill('10')
 page.locator('#weapon-attack-form button[type=submit]').click()
 assert 'Vow of Enmity Advantage' in page.locator('body').inner_text()
 assert 'Hunter’s Mark +' in page.locator('body').inner_text()
 page.locator('[data-action=nav][data-tab=sheet]:visible').first.click()
 page.locator('[data-action=paladin-capstone]').click()
 assert 'Avenging Angel' in page.locator('body').inner_text()
 library();reopen('Vengeance 2024')
 assert 'Active vow: Dire Wolf' in page.locator('body').inner_text()
 library()
 create('Glory 2024','oath-of-glory',20)
 assert page.locator('[data-action=glory-athlete]').is_visible()
 page.locator('[data-action=glory-athlete]').click()
 assert page.locator('[data-action=glory-athlete-end]').is_enabled()
 page.locator('[data-action=glory-defense]').click()
 assert 'Glorious Defense' in page.locator('body').inner_text()
 page.locator('[data-action=paladin-capstone]').click()
 assert 'Living Legend' in page.locator('body').inner_text()
 library();reopen('Glory 2024')
 assert page.locator('[data-action=glory-athlete-end]').is_enabled()
 library()
 create('Ancients 2024','oath-of-the-ancients',20)
 page.locator('[data-action=ancients-wrath]').click()
 assert "Nature's Wrath" in page.locator('body').inner_text()
 page.locator('#hp-amount').fill('11')
 page.locator('[data-action=damage]').click()
 page.locator('#damage-type').select_option('Radiant')
 assert page.locator('#damage-undying').is_visible()
 page.locator('[data-action=damage-apply]').click()
 assert '11 Radiant → 5' in page.locator('body').inner_text()
 page.locator('[data-action=paladin-capstone]').click()
 assert 'Elder Champion' in page.locator('body').inner_text()
 page.set_viewport_size({'width':390,'height':844})
 assert page.locator('[data-action=ancients-wrath]').is_visible()
 assert page.evaluate('document.documentElement.scrollWidth<=window.innerWidth+2'), 'Mobile layout has horizontal overflow'
 (BASE/'test-output').mkdir(exist_ok=True)
 page.screenshot(path=str(BASE/'test-output/milestone18-15-ancients-mobile.png'),full_page=True)
 assert not errors,errors
 browser.close()
print('PASS: All three newly-added PHB Paladin oaths, class UI, attack roll, damage, save/reopen and 390px layout')
